using GitGavel.System2.Abstractions;

namespace GitGavel.System2.Providers;

public class MockLlmClient : ILlmClient
{
    private readonly Func<LlmRequest, LlmResponse>? _responseHandler;

    public MockLlmClient(Func<LlmRequest, LlmResponse>? responseHandler = null)
    {
        _responseHandler = responseHandler;
    }

    public Task<LlmResponse> GenerateAsync(LlmRequest request, CancellationToken ct = default)
    {
        if (_responseHandler != null)
        {
            return Task.FromResult(_responseHandler(request));
        }

        // Default mock response with a valid JSON array of findings
        var sampleJson = """
        [
          {
            "title": "Mock Detected Finding",
            "summary": "This is a simulated finding generated by MockLlmClient.",
            "category": "Refactoring",
            "severity": "Medium",
            "filePath": "src/Sample.cs",
            "startLine": 10,
            "endLine": 25,
            "suggestedRemediation": "Refactor the logic to simplify branching.",
            "details": "Cyclomatic complexity exceeds threshold."
          }
        ]
        """;

        return Task.FromResult(new LlmResponse
        {
            Content = sampleJson,
            PromptTokens = 120,
            CompletionTokens = 85,
            DurationMs = 25,
            ModelUsed = request.Model
        });
    }
}
